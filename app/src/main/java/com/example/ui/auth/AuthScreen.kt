                Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    FeatureHighlightRow(
                        icon = Icons.Default.Subtitles,
                        title = "AI Clip Generator & Hooks",
                        subtitle = "Detect viral moments, animated 9:16 subtitles & 30+ language dubs."
                    )
                    FeatureHighlightRow(
                        icon = Icons.Default.AutoAwesome,
                        title = "AI Shorts UGC Studio",
                        subtitle = "Research products, write viral scripts & generate AI creator portraits."
                    )
                    FeatureHighlightRow(
                        icon = Icons.Default.MovieCreation,
                        title = "YouTube Studio & Thumbnails",
                        subtitle = "Title CTR picks, AI chat refinement, 16:9 thumbnails & chapters."
